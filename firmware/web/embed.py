#!/usr/bin/env python3
"""
Bakes an HTML file as a gzip byte array into a C++ header.

    python3 embed.py index.html ../src/webui_html.h WEBUI_HTML_GZ

The source is the HTML — that is where editing happens. This script is the generator,
not the truth. platformio.ini calls it as a pre-script so that the header cannot
go stale.
"""
import gzip, pathlib, sys

if len(sys.argv) != 4:
    sys.exit(f"Usage: {sys.argv[0]} <source.html> <target.h> <SYMBOL>")

src, dst, sym = pathlib.Path(sys.argv[1]), pathlib.Path(sys.argv[2]), sys.argv[3]

raw = src.read_bytes()
# mtime=0, so that the same content yields the same bytes and the build does not
# relink every time.
gz = gzip.compress(raw, 9, mtime=0)

lines = ["  " + ", ".join(f"0x{b:02x}" for b in gz[i:i + 16]) + ","
         for i in range(0, len(gz), 16)]

dst.write_text(
    "#pragma once\n"
    f"// GENERATED by firmware/web/embed.py from {src.name} — do not edit.\n"
    f"// Source {len(raw)} bytes, gzip {len(gz)} bytes ({100 * len(gz) // len(raw)} %).\n"
    "#include <Arduino.h>\n\n"
    f"constexpr size_t {sym}_LEN = {len(gz)};\n"
    f"const uint8_t {sym}[] PROGMEM = {{\n"
    + "\n".join(lines) + "\n};\n",
    encoding="utf-8")

print(f"{dst.name}: {len(raw)} -> {len(gz)} bytes gzip ({100 * len(gz) // len(raw)} %)")
