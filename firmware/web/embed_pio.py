# PlatformIO hook: bakes the UI of the MAIN FIRMWARE before every build.
import subprocess, sys, os
Import("env")  # noqa: F821
web = os.path.join(env.subst("$PROJECT_DIR"), "web")  # noqa: F821
r = subprocess.run([sys.executable, os.path.join(web, "embed.py"),
                    os.path.join(web, "index.html"),
                    os.path.join(env.subst("$PROJECT_DIR"), "src", "webui_html.h"),  # noqa: F821
                    "WEBUI_HTML_GZ"], capture_output=True, text=True)
print(r.stdout.strip() or r.stderr.strip())

# Firmware version for protocol, raw log and UI (2026-11-26): the git commit, "-dirty"
# with uncommitted changes. Written to src/build_id.h only when it changes, so an
# unchanged tree does not recompile; the file is git-ignored.
def _commit():
    try:
        root = env.subst("$PROJECT_DIR")  # noqa: F821
        h = subprocess.run(["git", "rev-parse", "--short=8", "HEAD"], cwd=root, capture_output=True, text=True).stdout.strip()
        d = subprocess.run(["git", "status", "--porcelain", "--untracked-files=no"], cwd=root, capture_output=True, text=True).stdout.strip()
        return (h or "unknown") + ("-dirty" if d else "")
    except Exception:
        return "unknown"
_bid = os.path.join(env.subst("$PROJECT_DIR"), "src", "build_id.h")  # noqa: F821
_txt = '#pragma once\n// Generated by web/embed_pio.py, git-ignored.\n#define FW_COMMIT "%s"\n' % _commit()
if not os.path.exists(_bid) or open(_bid).read() != _txt:
    open(_bid, "w").write(_txt)
print("build_id: " + _txt.split('"')[1])
